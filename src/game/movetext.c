void move_description(uint16_t move, char out[MOVETEXT_BYTES]) {
  const MoveInfo *m = &move_info[move];
  const char *text = L(effect_text_fr, effect_text_en)[m->effect];
  out[0] = 0;
  if (text && *text) {
    strcpy(out, text);
    if (!move_is_status(m) && m->effect_chance) {
      char pct[8], *p = pct + sizeof pct;
      unsigned v = m->effect_chance;
      *--p = 0;
      do *--p = (char)('0' + v % 10); while (v /= 10);
      strcat(strcat(strcat(out, " ("), p), " %)");
    }
  } else if (move_priority(m) > 0) {
    strcpy(out, L("Frappe en premier", "Strikes first"));
  } else if (move_priority(m) < 0) {
    strcpy(out, L("Agit en dernier", "Moves last"));
  } else if (m->high_crit) {
    strcpy(out, L("Coups critiques fréquents", "High critical-hit ratio"));
  } else {
    strcpy(out, L("Aucun effet particulier", "No added effect"));
  }
}
